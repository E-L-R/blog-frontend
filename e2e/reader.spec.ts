import { expect, test } from './fixtures.ts';

test.describe('readers', () => {
  test('read a post with its TL;DR and comments', async ({ page }) => {
    await page.goto('/');
    await expect(page.getByRole('complementary', { name: 'Demo mode' })).toBeVisible();
    await expect(page.getByRole('heading', { name: 'Latest posts' })).toBeVisible();

    await page
      .getByRole('link', { name: 'Why we replaced our data classes with Java records' })
      .click();
    await expect(page).toHaveURL(/\/posts\/why-we-replaced-our-data-classes-with-java-records$/);
    await expect(page).toHaveTitle(
      'Why we replaced our data classes with Java records · E-L-R Blog',
    );
    const tldr = page.getByRole('region', { name: 'TL;DR' });
    await expect(tldr).toContainText('AI-generated by');
    await expect(page.getByRole('heading', { name: 'What a record gives you' })).toBeVisible();
    await expect(page.getByRole('heading', { name: 'Comments (2)' })).toBeVisible();
    await expect(page.getByRole('link', { name: 'Sign in' }).last()).toBeVisible();
  });

  test('search and filter by tag', async ({ page }) => {
    await page.goto('/');
    await page.getByRole('searchbox', { name: 'Search posts' }).fill('elasticsearch');
    await page.getByRole('button', { name: 'Search' }).click();
    await expect(page).toHaveURL(/\?q=elasticsearch$/);
    await expect(page.getByRole('heading', { level: 2 })).toHaveText([
      'Full-text search in PostgreSQL before reaching for Elasticsearch',
    ]);

    await page.getByRole('link', { name: 'Tags', exact: true }).click();
    await page.getByRole('link', { name: /#Machine Learning/ }).click();
    await expect(
      page.getByRole('heading', { name: 'Posts tagged #Machine Learning' }),
    ).toBeVisible();
    await expect(page.getByRole('heading', { level: 2 })).toHaveCount(2);
  });

  test('deep links and reloads work (SPA fallback), unknown pages say not found', async ({
    page,
  }) => {
    await page.goto('/u/bob');
    await expect(page.getByRole('heading', { name: 'Bob Okafor', level: 1 })).toBeVisible();
    await page.reload();
    await expect(page.getByRole('heading', { name: 'Bob Okafor', level: 1 })).toBeVisible();
    await page.goto('/this/does/not/exist');
    await expect(page.getByRole('heading', { name: 'Page not found' })).toBeVisible();
  });

  test('watch the model finish a TL;DR', async ({ page }) => {
    await page.goto('/posts/attention-explained-one-matrix-at-a-time');
    const tldr = page.getByRole('region', { name: 'TL;DR' });
    await expect(tldr).toContainText('Our language model is writing a summary');
    await expect(tldr).toContainText('AI-generated by', { timeout: 20_000 });
  });

  test('send the security headers', async ({ page }) => {
    const response = await page.goto('/');
    const headers = response?.headers() ?? {};
    expect(headers['content-security-policy']).toContain("script-src 'self'");
    expect(headers['x-content-type-options']).toBe('nosniff');
    expect(headers['x-robots-tag']).toBe('noindex'); // demo data stays out of search engines
  });
});
