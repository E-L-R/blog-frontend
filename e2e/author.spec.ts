import { expect, signIn, test } from './fixtures.ts';

test.describe('authors', () => {
  test('write, publish, get a TL;DR, comment, sign out', async ({ page }) => {
    await signIn(page);

    await page.getByRole('link', { name: 'Write', exact: true }).click();
    await page.getByLabel('Title').fill('End-to-end tests catch what unit tests can’t');
    await page.getByLabel('Tags').fill('Testing, Playwright');
    await page
      .getByLabel('Content (Markdown)')
      .fill(
        'Unit tests check functions. End-to-end tests check that the pieces work together in a real browser.\n\n## Why\n\nService workers, headers and routing only exist there.',
      );
    await page.getByRole('tab', { name: 'Preview' }).click();
    await expect(
      page.getByRole('tabpanel', { name: 'Preview' }).getByRole('heading', { name: 'Why' }),
    ).toBeVisible();

    await page.getByRole('button', { name: 'Save and publish' }).click();
    await expect(page).toHaveURL(/\/write\/end-to-end-tests-catch-what-unit-tests-can-t$/);
    await expect(page.getByRole('button', { name: 'Unpublish' })).toBeVisible();
    const panel = page.getByRole('region', { name: 'TL;DR' });
    await expect(panel).toContainText('Written by the model.', { timeout: 20_000 });

    await page.getByRole('link', { name: 'View' }).click();
    await expect(page.getByRole('region', { name: 'TL;DR' })).toContainText('AI-generated by');
    await page.getByLabel('Add a comment').fill('Published from the end-to-end test.');
    await page.getByRole('button', { name: 'Post comment' }).click();
    await expect(page.getByRole('heading', { name: 'Comments (1)' })).toBeVisible();

    await page.getByRole('button', { name: 'Sign out' }).click();
    await expect(page.getByRole('link', { name: 'Sign in' }).first()).toBeVisible();
  });

  test('stay signed in across reloads and tabs', async ({ page, context }) => {
    await signIn(page);
    await page.goto('/dashboard');
    await page.reload();
    await expect(page.getByRole('heading', { name: 'My posts' })).toBeVisible();

    const second = await context.newPage();
    await second.goto('/settings');
    await expect(second.getByRole('heading', { name: 'Settings' })).toBeVisible();

    // Signing out in one tab signs out the other.
    await second.getByRole('button', { name: 'Sign out' }).click();
    await expect(page.getByRole('link', { name: 'Sign in' }).first()).toBeVisible();
  });

  test('protect unsaved work', async ({ page }) => {
    await signIn(page);
    await page.goto('/write/notes-on-container-image-layers');
    await page.getByLabel('Title').fill('Changed but not saved');
    await page.getByRole('link', { name: 'Posts', exact: true }).click();
    const dialog = page.getByRole('dialog', { name: 'Leave without saving?' });
    await expect(dialog).toBeVisible();
    await dialog.getByRole('button', { name: 'Cancel' }).click();
    await expect(page).toHaveURL(/\/write\/notes-on-container-image-layers$/);
  });
});
