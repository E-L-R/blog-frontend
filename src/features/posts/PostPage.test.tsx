import { screen, within } from '@testing-library/react';
import { describe, expect, it } from 'vitest';
import { renderApp, signInAs } from '../../test/renderApp.tsx';
import { db, resetMockApi } from '../../test/server.ts';

const RECORDS = 'why-we-replaced-our-data-classes-with-java-records';

describe('PostPage', () => {
  it('shows the post with its metadata, TL;DR and rendered content', async () => {
    renderApp(`/posts/${RECORDS}`);
    expect(
      await screen.findByRole('heading', {
        level: 1,
        name: 'Why we replaced our data classes with Java records',
      }),
    ).toBeInTheDocument();
    expect(screen.getByRole('link', { name: 'Alice Martin' })).toHaveAttribute('href', '/u/alice');
    const tldr = screen.getByRole('region', { name: 'TL;DR' });
    expect(within(tldr).getByText(/AI-generated by/)).toBeInTheDocument();
    expect(
      screen.getByRole('heading', { level: 2, name: 'What a record gives you' }),
    ).toBeInTheDocument();
    expect(document.title).toBe('Why we replaced our data classes with Java records · E-L-R Blog');
  });

  it('labels author-written TL;DRs as such', async () => {
    renderApp('/posts/full-text-search-in-postgresql-before-reaching-for-elasticsearch');
    const tldr = await screen.findByRole('region', { name: 'TL;DR' });
    expect(within(tldr).getByText('Written by the author.')).toBeInTheDocument();
    expect(within(tldr).queryByText(/AI-generated/)).not.toBeInTheDocument();
  });

  it('shows readers nothing for a failed TL;DR', async () => {
    renderApp('/posts/testcontainers-made-our-integration-tests-honest');
    await screen.findByRole('heading', { level: 1 });
    expect(screen.queryByRole('region', { name: 'TL;DR' })).not.toBeInTheDocument();
  });

  it('polls while the model writes the TL;DR, then shows it', async () => {
    let now = Date.now();
    resetMockApi({ now: () => now, tldrDelayMs: 1000 });
    renderApp('/posts/attention-explained-one-matrix-at-a-time');
    expect(
      await screen.findByText('Our language model is writing a summary of this post…'),
    ).toBeInTheDocument();
    now += 10_000; // the seed's TL;DR is due 8 s after start
    expect(await screen.findByText(/AI-generated by/, {}, { timeout: 6000 })).toBeInTheDocument();
  }, 10_000);

  it('sanitizes the HTML before showing it (defense in depth)', async () => {
    const post = db.postBySlug(RECORDS)!;
    post.contentMarkdown =
      'Hello <img src="x" onerror="window.__pwned = true"> <script>window.__pwned = true</script>';
    renderApp(`/posts/${RECORDS}`);
    await screen.findByText('Hello');
    expect(document.querySelector('.prose')?.innerHTML).not.toMatch(/onerror|<script/);
  });

  it('answers unknown and unpublished posts with not found', async () => {
    renderApp('/posts/notes-on-container-image-layers');
    expect(await screen.findByRole('heading', { name: 'Page not found' })).toBeInTheDocument();
  });

  it('lets the author preview a draft and edit it', async () => {
    await signInAs('demo');
    renderApp('/posts/notes-on-container-image-layers?preview=1');
    expect(
      await screen.findByText('This is a draft preview. Only you can see it.'),
    ).toBeInTheDocument();
    expect(screen.getByRole('link', { name: 'Edit post' })).toHaveAttribute(
      'href',
      '/write/notes-on-container-image-layers',
    );
    expect(screen.queryByRole('heading', { name: /Comments/ })).not.toBeInTheDocument();
  });

  it('shows the edit link only to people who may edit', async () => {
    await signInAs('bob');
    renderApp(`/posts/${RECORDS}`);
    await screen.findByRole('heading', { level: 1 });
    expect(screen.queryByRole('link', { name: 'Edit post' })).not.toBeInTheDocument();
  });
});
