import type { TldrView } from '../../api/schemas.ts';
import { config } from '../../config/env.ts';
import styles from '../posts/posts.module.css';

/**
 * The TL;DR as readers see it. Model-written summaries are always labeled as such (AI disclosure),
 * and nothing is shown when there is no summary (drafts, failures): that's the author's business.
 */
export function TldrSummary({ tldr }: { tldr: TldrView }) {
  const summary = tldr.summary?.trim();
  if (tldr.state === 'PENDING') {
    return (
      <section className={styles.tldr} aria-labelledby="tldr-heading" aria-live="polite">
        <h2 id="tldr-heading">TL;DR</h2>
        {summary ? <p>{summary}</p> : <p>Our language model is writing a summary of this post…</p>}
        <p className={styles.tldrSource}>
          {summary ? 'An updated summary is being written.' : 'This usually takes a few seconds.'}
        </p>
      </section>
    );
  }
  if ((tldr.state !== 'READY' && tldr.state !== 'MANUAL') || !summary) {
    return null;
  }
  return (
    <section className={styles.tldr} aria-labelledby="tldr-heading" aria-live="polite">
      <h2 id="tldr-heading">TL;DR</h2>
      <p>{summary}</p>
      <p className={styles.tldrSource}>
        {tldr.state === 'READY' ? (
          <>
            AI-generated by <a href={config.modelRepoUrl}>our own language model</a>. It can be
            wrong; the post is the source of truth.
          </>
        ) : (
          'Written by the author.'
        )}
      </p>
    </section>
  );
}
